const BY_ALPHA2 = new Map(COUNTRIES.map((c) => [String(c.alpha2), c]));
const BY_ALPHA3 = new Map(COUNTRIES.map((c) => [c.alpha3, c]));
const BY_NUMERIC = new Map(COUNTRIES.map((c) => [c.numeric, c]));

/** Resolves alpha-2, alpha-3 or numeric codes; returns undefined when unknown. */
export function findCountry(code: string): Country | undefined {
  const normalized = code.trim().toUpperCase();
  return (
    BY_ALPHA2.get(normalized) ?? BY_ALPHA3.get(normalized) ?? BY_NUMERIC.get(normalized.padStart(3, "0"))
  );
}

export function requireCountry(code: string): Country {
  const found = findCountry(code);
  if (!found) throw ValidationError.single("countryCode", `unknown country "${code}"`);
  return found;
}

export function countryCode(value: string): CountryCode {
  return requireCountry(value).alpha2;
}

export function isEuMember(code: string): boolean {
  return findCountry(code)?.euMember ?? false;
}

/** VAT prefix for the country, which is the alpha-2 code except for Greece. */
export function vatPrefixFor(code: string): string | undefined {
  const found = findCountry(code);
  if (!found) return undefined;
  return found.vatPrefix ?? String(found.alpha2);
}

/** The country a VAT prefix belongs to ("EL" -> Greece, "DE" -> Germany). */
export function countryForVatPrefix(prefix: string): Country | undefined {
  const normalized = prefix.trim().toUpperCase();
  return COUNTRIES.find(
    (candidate) => (candidate.vatPrefix ?? String(candidate.alpha2)) === normalized,
  );
}

export function subdivisionsOf(code: string): readonly CountrySubdivision[] {
  return findCountry(code)?.subdivisions ?? [];
}

export function findSubdivision(code: string, region: string): CountrySubdivision | undefined {
  const normalized = region.trim().toUpperCase();
  return subdivisionsOf(code).find(
    (s) => s.code === normalized || s.name.toUpperCase() === normalized,
  );
}
