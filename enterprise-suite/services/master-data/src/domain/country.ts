/**
 * Country reference data (ISO 3166-1) with the per-country rules master data
 * needs: default currency, postal-code shape and regrouping, whether a
 * subdivision is part of a deliverable address, EU/VAT membership, and the
 * layout used to render a postal label.
 *
 * This is reference data, not tenant data: it is identical for every tenant
 * and is treated as read-only by the services. Tenants extend it by creating
 * code lists, never by editing these rows.
 */

export type CountryCode = Brand<string, "CountryCode">;

/**
 * How a compacted postal code is regrouped for display.
 *
 * `groups` sizes the leading chunks (the remainder becomes the last chunk);
 * `tail` instead separates the final N characters, which is what variable
 * length codes such as UK outcodes need. Reformatting only happens when the
 * compacted length is in `lengths`, so partially entered codes are left alone
 * rather than mangled.
 */
export interface PostalLayout {
  readonly groups?: readonly number[];
  readonly tail?: number;
  readonly separator: string;
  readonly lengths: readonly number[];
  /** Prefix re-applied after compaction, e.g. Latvian "LV-1010". */
  readonly prefix?: string;
}

/** Named label layouts; `renderAddress` resolves the placeholders. */
export type AddressLayout =
  | "postal-city" // most of continental Europe: "1010 Wien"
  | "city-region-postal" // US/CA/AU: "Boston MA 02110"
  | "city-then-postal" // UK/IE/IN: city and postcode on their own lines
  | "postal-region-city"; // JP/CN: largest unit first

export interface CountrySubdivision {
  readonly code: string;
  readonly name: string;
  readonly type: "state" | "province" | "territory" | "district" | "region";
}

export interface Country {
  readonly alpha2: CountryCode;
  readonly alpha3: string;
  readonly numeric: string;
  readonly name: string;
  /** ISO 4217 code of the country's primary legal tender. */
  readonly currency: string;
  readonly callingCode: string;
  readonly euMember: boolean;
  /** VAT registration prefix where it differs from alpha2 (Greece uses EL). */
  readonly vatPrefix?: string;
  readonly postalPattern?: RegExp;
  readonly postalExample?: string;
  readonly postalRequired: boolean;
  readonly postalLayout?: PostalLayout;
  /** A subdivision is mandatory for a deliverable address. */
  readonly regionRequired: boolean;
  readonly addressLayout: AddressLayout;
  /** Present only where the closed list is short and stable enough to enforce. */
  readonly subdivisions?: readonly CountrySubdivision[];
}

